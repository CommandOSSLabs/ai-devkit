#!/usr/bin/env python3
"""gen-ai-skill-maps.py — write docs/ai/skills/<family>.md, one page per explorer category.

The pages are generated from what the repo already states, so they cannot drift: each skill's
frontmatter (name, description, version, user-invoked or not), its references/ and scripts/
files, the cmk: names its SKILL.md and references cite, its family (lib/skill-types.ts
CATEGORY_MAP) and its tier (skills/agent-vendors/references/packs.md). docs/ai/skills/README.md
and conventions.md stay hand-written. Run from the repo root; rerun after any skill changes.
"""
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
OUT = "docs/ai/skills"


def text(p):
    with open(p, encoding="utf-8") as f:
        return f.read()


types = text("lib/skill-types.ts")
lab_src = types[types.index("CATEGORY_LABELS"):]
labels = dict(re.findall(r'^\s+([a-z]+): "([^"]+)",', lab_src[:lab_src.index("};")], re.M))
cmap_src = types[types.index("CATEGORY_MAP"):]
cmap = dict(re.findall(r'^\s+"?([a-z0-9-]+)"?: "([a-z]+)",', cmap_src[:cmap_src.index("};")], re.M))

packs = {}
packs_md = text("skills/agent-vendors/references/packs.md")
section = packs_md[packs_md.index("## Packs"):packs_md.index("## Choosing")]
for row in section.splitlines():
    m = re.match(r"\| `([a-z]+)` \| (.+?) \|", row)
    if m:
        for s in re.findall(r"`cmk:([a-z0-9-]+)`", m.group(2)):
            packs[s] = m.group(1)


def frontmatter(body):
    m = re.match(r"---\n(.*?)\n---\n", body, re.S)
    return dict(re.findall(r"^([a-z-]+):\s*(.*)$", m.group(1), re.M)) if m else {}


families = {}
for d in sorted(glob.glob("skills/*/SKILL.md")):
    sid = d.split("/")[1]
    body = text(d)
    fm = frontmatter(body)
    refs = sorted(os.path.relpath(p, f"skills/{sid}") for p in glob.glob(f"skills/{sid}/references/**/*.md", recursive=True))
    scripts = sorted(os.path.relpath(p, f"skills/{sid}") for p in glob.glob(f"skills/{sid}/scripts/*")
                     if os.path.isfile(p) and not os.path.basename(p).startswith("test_"))
    corpus = body + "".join(text(f"skills/{sid}/{r}") for r in refs)
    cites = sorted(set(re.findall(r"cmk:([a-z][a-z0-9-]*)", corpus)) - {sid})
    cites = [c for c in cites if os.path.isdir(f"skills/{c}")]
    families.setdefault(cmap.get(sid, "other"), []).append({
        "id": sid, "name": fm.get("name", f"cmk:{sid}"), "version": fm.get("version", "?"),
        "desc": fm.get("description", ""), "user": fm.get("disable-model-invocation") == "true",
        "tier": f"pack `{packs[sid]}`" if sid in packs else "core",
        "refs": refs, "scripts": scripts, "cites": cites,
        "evidence": [f for f in ("TESTS.md", "eval.json") if os.path.exists(f"skills/{sid}/{f}")],
    })

for old in glob.glob(f"{OUT}/*.md"):
    if os.path.basename(old) not in ("README.md", "conventions.md"):
        os.remove(old)

for fam, skills in sorted(families.items()):
    lines = [f"# {labels.get(fam, fam)} skills", "",
             "<!-- Generated by scripts/gen-ai-skill-maps.py — edit the skills, then rerun. -->", "",
             f"{len(skills)} skills. Each entry points at the package; the package is the source of truth.", ""]
    for s in skills:
        mode = "user-invoked (`/" + s["name"] + "`)" if s["user"] else "model-invoked"
        lines += [f"## {s['name']}", "",
                  f"{mode} · {s['tier']} · v{s['version']}", "",
                  s["desc"], "",
                  f"- **Where:** `skills/{s['id']}/SKILL.md`"]
        if s["refs"]:
            lines.append("- **References:** " + ", ".join(f"`{r}`" for r in s["refs"]))
        if s["scripts"]:
            lines.append("- **Scripts:** " + ", ".join(f"`{r}`" for r in s["scripts"]))
        if s["cites"]:
            lines.append("- **Cites:** " + ", ".join(f"`cmk:{c}`" for c in s["cites"]))
        if s["evidence"]:
            lines.append("- **Evidence:** " + ", ".join(f"`{e}`" for e in s["evidence"]))
        lines.append("")
    with open(f"{OUT}/{fam}.md", "w", encoding="utf-8") as f:
        f.write("\n".join(lines).rstrip() + "\n")
    print(f"{OUT}/{fam}.md: {len(skills)}")
